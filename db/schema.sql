-- QA Automation Intelligence data schema (PostgreSQL).
-- Created once per project schema ("live" = real Playwright runs, "demo" =
-- synthetic history); the repository sets search_path before running this.

CREATE TABLE IF NOT EXISTS features (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(100) NOT NULL UNIQUE,
    criticality        SMALLINT NOT NULL CHECK (criticality BETWEEN 1 AND 5),
    requirements_count INTEGER NOT NULL CHECK (requirements_count > 0)
);

CREATE TABLE IF NOT EXISTS environments (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS test_cases (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_id     INTEGER NOT NULL REFERENCES features(id),
    name           VARCHAR(200) NOT NULL,
    layer          VARCHAR(10) NOT NULL CHECK (layer IN ('UI', 'API')),
    requirement_no INTEGER,
    automated      BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (feature_id, name)
);

CREATE TABLE IF NOT EXISTS test_runs (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at     TIMESTAMP NOT NULL,
    environment_id INTEGER NOT NULL REFERENCES environments(id),
    build_number   INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS test_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       INTEGER NOT NULL REFERENCES test_runs(id),
    test_case_id INTEGER NOT NULL REFERENCES test_cases(id),
    status       VARCHAR(10) NOT NULL CHECK (status IN ('PASSED', 'FAILED', 'SKIPPED')),
    duration_ms  INTEGER NOT NULL
);

-- failure / skip reason (first line, truncated); NULL for passes and synthetic data
ALTER TABLE test_results ADD COLUMN IF NOT EXISTS message VARCHAR(500);

CREATE TABLE IF NOT EXISTS api_endpoints (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_id INTEGER NOT NULL REFERENCES features(id),
    method     VARCHAR(10) NOT NULL,
    path       VARCHAR(200) NOT NULL,
    UNIQUE (method, path)
);

CREATE TABLE IF NOT EXISTS api_metrics (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id    INTEGER NOT NULL REFERENCES api_endpoints(id),
    environment_id INTEGER NOT NULL REFERENCES environments(id),
    measured_at    TIMESTAMP NOT NULL,
    latency_ms     REAL NOT NULL,
    status_code    SMALLINT NOT NULL
);

CREATE TABLE IF NOT EXISTS code_changes (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_id    INTEGER NOT NULL REFERENCES features(id),
    changed_at    TIMESTAMP NOT NULL,
    lines_changed INTEGER NOT NULL
);

-- wall-clock run duration (NULL when unknown)
ALTER TABLE test_runs ADD COLUMN IF NOT EXISTS duration_ms INTEGER;

CREATE TABLE IF NOT EXISTS requirements (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_id  INTEGER NOT NULL REFERENCES features(id),
    req_no      INTEGER NOT NULL,
    description VARCHAR(300) NOT NULL,
    UNIQUE (feature_id, req_no)
);

-- A use case is an end-to-end user journey made of requirement steps that can
-- span several features.
CREATE TABLE IF NOT EXISTS use_cases (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150) NOT NULL UNIQUE,
    priority    SMALLINT NOT NULL CHECK (priority BETWEEN 1 AND 5),
    description VARCHAR(300)
);

CREATE TABLE IF NOT EXISTS use_case_steps (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    use_case_id    INTEGER NOT NULL REFERENCES use_cases(id) ON DELETE CASCADE,
    step_no        INTEGER NOT NULL,
    requirement_id INTEGER NOT NULL REFERENCES requirements(id),
    UNIQUE (use_case_id, step_no)
);

CREATE INDEX IF NOT EXISTS ix_results_run ON test_results(run_id);
CREATE INDEX IF NOT EXISTS ix_results_case ON test_results(test_case_id);
CREATE INDEX IF NOT EXISTS ix_metrics_endpoint_time ON api_metrics(endpoint_id, measured_at);
CREATE INDEX IF NOT EXISTS ix_runs_started ON test_runs(started_at);
