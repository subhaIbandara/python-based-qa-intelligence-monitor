"""Dashboard user accounts, validated against PostgreSQL.

Passwords are stored as PBKDF2-HMAC-SHA256 with a per-user random salt
(standard library only). Login failures return one generic message, and an
account is locked for LOCK_SECONDS after MAX_FAILED consecutive failures.
"""
import hashlib
import hmac
import secrets
from datetime import datetime, timedelta

from db.repository import connect

ITERATIONS = 390_000
MAX_FAILED = 5
LOCK_SECONDS = 60

DDL = """
CREATE TABLE IF NOT EXISTS public.app_users (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50) NOT NULL UNIQUE,
    full_name       VARCHAR(100),
    password_hash   VARCHAR(64) NOT NULL,
    salt            VARCHAR(32) NOT NULL,
    iterations      INTEGER NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until    TIMESTAMP,
    last_login      TIMESTAMP,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""

INVALID = "Invalid username or password."


def _hash(password: str, salt: str, iterations: int) -> str:
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), iterations).hex()


def ensure_table(conn) -> None:
    with conn.cursor() as cursor:
        cursor.execute(DDL)
    conn.commit()


def user_count() -> int:
    conn = connect()
    try:
        ensure_table(conn)
        with conn.cursor() as cursor:
            cursor.execute("SELECT COUNT(*) FROM public.app_users")
            return cursor.fetchone()[0]
    finally:
        conn.close()


def set_password(username: str, password: str, full_name: str = None) -> None:
    """Create the user, or reset the password of an existing one."""
    if len(password) < 8:
        raise ValueError("Password must be at least 8 characters.")
    salt = secrets.token_hex(16)
    pw_hash = _hash(password, salt, ITERATIONS)
    conn = connect()
    try:
        ensure_table(conn)
        with conn.cursor() as cursor:
            cursor.execute("""
                INSERT INTO public.app_users (username, full_name, password_hash, salt, iterations)
                VALUES (%s, %s, %s, %s, %s)
                ON CONFLICT (username) DO UPDATE
                   SET password_hash = EXCLUDED.password_hash, salt = EXCLUDED.salt,
                       iterations = EXCLUDED.iterations, failed_attempts = 0, locked_until = NULL,
                       full_name = COALESCE(EXCLUDED.full_name, app_users.full_name)
            """, (username.strip(), full_name, pw_hash, salt, ITERATIONS))
        conn.commit()
    finally:
        conn.close()


def authenticate(username: str, password: str) -> tuple:
    """Returns (ok, message_or_display_name)."""
    username = (username or "").strip()
    if not username or not password:
        return False, "Enter your username and password."
    conn = connect()
    try:
        ensure_table(conn)
        with conn.cursor() as cursor:
            cursor.execute("""SELECT id, full_name, password_hash, salt, iterations, failed_attempts, locked_until
                              FROM public.app_users WHERE username = %s""", (username,))
            row = cursor.fetchone()
            if row is None:
                _hash(password, secrets.token_hex(16), ITERATIONS)   # same cost → no user-existence timing leak
                return False, INVALID
            uid, full_name, pw_hash, salt, iterations, failed, locked_until = row
            now = datetime.now()
            if locked_until and locked_until > now:
                wait = int((locked_until - now).total_seconds()) + 1
                return False, f"Too many failed attempts. Try again in {wait} s."
            if hmac.compare_digest(_hash(password, salt, iterations), pw_hash):
                cursor.execute("UPDATE public.app_users SET failed_attempts = 0, locked_until = NULL, "
                               "last_login = %s WHERE id = %s", (now, uid))
                conn.commit()
                return True, full_name or username
            failed += 1
            lock = now + timedelta(seconds=LOCK_SECONDS) if failed >= MAX_FAILED else None
            cursor.execute("UPDATE public.app_users SET failed_attempts = %s, locked_until = %s WHERE id = %s",
                           (0 if lock else failed, lock, uid))
            conn.commit()
            if lock:
                return False, f"Too many failed attempts. Account locked for {LOCK_SECONDS} s."
            return False, INVALID
    finally:
        conn.close()
